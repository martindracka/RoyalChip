// Entry point of the "casino" Appwrite Function.
// The browser calls it with { action, payload }. Everything that changes chips runs here,
// with a server API key – players themselves have no write access to balances or bets.
import { Client, Users } from 'node-appwrite'
import { createAppwriteDb } from './appwriteDb.js'
import { handle } from './handler.js'
import { HttpError } from './errors.js'

const MAX_BODY_LENGTH = 2000

function parseBody(req) {
  const text = req.bodyText || req.body || ''
  if (typeof text !== 'string' || text.length > MAX_BODY_LENGTH) return null
  try {
    return JSON.parse(text || '{}')
  } catch {
    return null
  }
}

export default async ({ req, res, error }) => {
  // Set by Appwrite for the logged-in caller. Headers starting with x-appwrite- cannot be
  // faked by the client, so this is a trusted identity – unlike anything in the body.
  const userId = req.headers['x-appwrite-user-id']
  if (!userId) return res.json({ error: 'Please log in first.' }, 401)

  const body = parseBody(req)
  if (!body || typeof body.action !== 'string') return res.json({ error: 'Invalid request' }, 400)

  // Short-lived key generated by Appwrite for this execution, limited to the function's scopes.
  const client = new Client()
    .setEndpoint(process.env.APPWRITE_FUNCTION_API_ENDPOINT)
    .setProject(process.env.APPWRITE_FUNCTION_PROJECT_ID)
    .setKey(req.headers['x-appwrite-key'])

  const db = createAppwriteDb(client, process.env.DATABASE_ID || 'casino')

  try {
    // The account name is only needed when a new profile is created.
    const user = body.action === 'profile.init' ? await new Users(client).get({ userId }) : null
    const data = await handle({ db, userId, user }, body.action, body.payload ?? {})
    return res.json({ data })
  } catch (e) {
    if (e instanceof HttpError) return res.json({ error: e.message }, e.status)
    error(e?.stack || String(e)) // visible only in the Appwrite console logs
    return res.json({ error: 'Something went wrong on the server. Please try again.' }, 500)
  }
}
